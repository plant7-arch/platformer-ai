"""The level generator (levelgen.py), the beatability search (levelplan.py) and the many-level evaluation printout."""
import random

import numpy as np
import pytest

from platformer_ai import levelcheck, levelgen, levelplan, levelsettings, train


def grid_of(text):
    rows, _ = levelcheck.split_text(text)
    return np.array([list(r) for r in rows])


@pytest.mark.parametrize("tier", levelgen.TIERS)
def test_generated_levels_are_clean_and_shaped_by_tier(tier):
    rng = random.Random(tier)
    for _ in range(40):
        text = levelgen.generate(tier, rng)
        rep = levelcheck.check(text)
        assert not rep.errors and not rep.warnings, (text, rep.errors, rep.warnings)
        g = grid_of(text)
        h, w = g.shape
        d = levelsettings.TIER_DEFAULTS[tier]
        assert d["height"][0] <= h <= d["height"][1]
        assert d["width"][0] <= w <= d["width"][1]
        assert (g == "P").sum() == 1 and (g[:, -1] == "G").sum() == 2          # spawn, flag at the right edge
        assert np.argwhere(g == "P")[0][1] <= 2
        assert levelgen.tier_of(text) == tier


def test_tier_features():
    """Tier 1 has no stepping stones / upper platforms / riders; tier 3 has riders somewhere."""
    rng = random.Random(5)
    riders = 0
    for _ in range(40):
        t1 = levelgen.generate(1, rng)
        _, plats, enemies, _ = levelcheck.layout(t1, 6.0, 3.0)
        assert len(enemies) <= 1 and len(plats) <= 1 and not any(e.ride >= 0 or e.run for e in enemies)
        _, _, enemies, _ = levelcheck.layout(levelgen.generate(3, rng), 6.0, 3.0)
        riders += sum(e.ride >= 0 for e in enemies)
    assert riders > 0


def test_same_seed_same_levels():
    a = [levelgen.generate(t, random.Random(42)) for t in levelgen.TIERS]
    b = [levelgen.generate(t, random.Random(42)) for t in levelgen.TIERS]
    assert a == b


def test_tier_of():
    assert levelgen.tier_of("gen/train/t2_0013.txt") == 2
    assert levelgen.tier_of("docs/levels/01_walk.txt") is None
    assert levelgen.tier_of("....\n\n# generated by levelgen: tier 3\n") == 3


def test_write_set_replaces_only_generated_files(tmp_path):
    (tmp_path / "t1_9999.txt").write_text("old")
    (tmp_path / "mine.txt").write_text("keep")
    rng = random.Random(0)
    paths = levelgen.write_set([(t, levelgen.generate(t, rng)) for t in (1, 2)], str(tmp_path))
    assert sorted(p.name for p in tmp_path.iterdir()) == ["mine.txt", "t1_0000.txt", "t2_0001.txt"]
    assert len(paths) == 2


def lv(*rows):
    return "\n".join(rows) + "\n"


def test_search_finishes_what_the_physics_allow_and_nothing_more():
    cases = [
        (True, lv("....................", "..P................G", "#######...##########", "#######...##########")),
        (False, lv("....................", "..P................G", "#######.....########", "#######.....########")),
        (True, lv("....................", "...........##......G", "..P........#########", "####################")),
        (False, lv("...........###.....G", "...........#########", "..P........#########", "####################")),
    ]
    ok = levelplan.solvable([t for _, t in cases], trials=1)
    assert ok == [want for want, _ in cases]


def test_search_finishes_generated_levels():
    rng = random.Random(11)
    texts = [levelgen.generate(t, rng) for t in levelgen.TIERS]
    ok, steps = levelplan.solvable(texts, with_steps=True)
    assert all(ok) and all(0 < s < 900 for s in steps)


def fake_eval(n):
    rng = np.random.default_rng(0)
    per = dict(ret=rng.random(n), coins=rng.random(n), goal=np.linspace(0, 1, n), max_x=rng.random(n) * 50,
               length=rng.random(n), finished=np.ones(n))
    return dict(ret=0.5, coins=1.0, goal=0.5, max_x=20.0, length=300.0, per_level=per)


def test_eval_lines_per_level_for_few_levels():
    names = [f"docs/levels/0{i}.txt" for i in range(3)]
    lines = train.eval_lines("greedy", fake_eval(3), names, 513)
    assert len(lines) == 4 and "01.txt" in lines[2]


def test_eval_lines_summary_for_many_levels():
    names = [f"gen/train/t{1 + i % 3}_{i:04d}.txt" for i in range(30)]
    lines = train.eval_lines("greedy", fake_eval(30), names, 600)
    text = "\n".join(lines)
    assert len(lines) == 1 + 3 + 2
    assert "tier 1" in text and "tier 3" in text and "levels by goal rate" in text and "worst: t1_0000.txt" in text


def test_eval_envs_and_level_summary():
    assert train.eval_envs(3, 4) == 513 and train.eval_envs(300, 4) == 1200 and train.eval_envs(7, 100) == 700
    names = [f"gen/train/t{1 + i % 3}_{i:04d}.txt" for i in range(30)]
    assert train.level_summary(names, ["gen/train/"]) == "30 levels from gen/train/ (tier 1: 10, tier 2: 10, tier 3: 10)"
    assert train.level_summary(["a.txt"], None) == "1 level: a.txt"


def test_log_interval_by_verbosity():
    assert train.log_interval(762, 1, None) == 19          # ~40 progress lines per run
    assert train.log_interval(12, 1, None) == 1
    assert train.log_interval(762, 2, None) == 1           # every update
    assert train.log_interval(762, 0, 50) == 50 and train.log_interval(762, 2, 5) == 5     # --log-every wins


def test_eval_compact_and_every_level():
    line = train.eval_compact(40, [("greedy ", fake_eval(3)), ("UNSEEN greedy", fake_eval(3))])
    assert line.startswith("    EVAL upd   40  greedy goal 0.50") and "UNSEEN greedy goal" in line and "\n" not in line
    names = [f"gen/train/t1_{i:04d}.txt" for i in range(30)]
    assert len(train.eval_lines("greedy", fake_eval(30), names, 600, every_level=True)) == 31


def test_levelplan_command_line_names_files_and_refuses_broken_ones(tmp_path, capsys, caplog):
    good, bad = tmp_path / "good.txt", tmp_path / "bad.txt"
    good.write_text("..........\n.P......G.\n##########\n")
    bad.write_text("..........\n.p.P..P...\n##########\n")
    assert levelplan.main([str(good)]) == 0
    assert levelplan.main([str(good), str(bad), str(tmp_path / "missing.txt")]) == 2      # no search, no traceback
    err = capsys.readouterr().err
    assert "bad.txt has 2 problems" in err and "cannot read the level file" in err
    nogoal = tmp_path / "nogoal.txt"
    nogoal.write_text("..........\n.P........\n##########\n")
    caplog.clear()
    assert levelplan.main([str(nogoal)]) == 1
    warnings = [r.getMessage() for r in caplog.records if "no-goal" in r.getMessage()]
    assert len(warnings) == 1 and "nogoal.txt" in warnings[0]          # once, naming the file (not 'candidate 0')


